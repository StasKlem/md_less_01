import Foundation

/// Контракт преобразования исходного файла в структурированную модель документа для RAG-конвейера.
protocol DocumentParser {
    /// Разбирает локальный URL документа и возвращает нормализованное представление.
    /// - Parameter url: Файловый URL исходного документа.
    /// - Returns: Содержимое документа в разобранном виде, готовое к чанкингу.
    /// - Throws: Ошибка чтения или парсинга.
    func parse(url: URL) throws -> ParsedDocument
}

/// Контракт разбиения разобранного документа на черновики чанков по выбранной стратегии.
protocol ChunkingStrategy {
    /// Идентификатор стратегии для отчетов, выбора и сравнения.
    var kind: ChunkingStrategyType { get }
    /// Формирует чанки из разобранного документа.
    /// - Parameter document: Разобранный документ, который нужно разбить на чанки.
    /// - Returns: Черновики чанков, подготовленные для эмбеддингов и сохранения.
    /// - Throws: Ошибка, если генерацию чанков не удалось завершить.
    func makeChunks(document: ParsedDocument) throws -> [ChunkDraft]
}

/// Контракт генерации векторных эмбеддингов из текстового входа.
protocol EmbeddingProvider {
    /// Создает эмбеддинги для набора текстов с использованием переданных настроек RAG.
    /// - Parameters:
    ///   - texts: Входные тексты для векторизации.
    ///   - settings: Runtime-настройки, определяющие поведение генерации эмбеддингов.
    /// - Returns: Векторы эмбеддингов, соответствующие элементам `texts` по индексам.
    /// - Throws: Ошибка выполнения запроса на эмбеддинги.
    func embed(texts: [String], settings: RAGSettings) async throws -> [[Float]]
}

/// Контракт сохранения и поиска по векторизованным чанкам документов.
protocol VectorStore {
    /// Очищает все проиндексированные векторы и связанные метаданные.
    /// - Throws: Ошибка, если операция сброса не удалась.
    func reset() async throws
    /// Вставляет или обновляет векторизованные чанки документов.
    /// - Parameter chunks: Чанки для вставки или обновления в хранилище.
    /// - Throws: Ошибка сохранения.
    func upsert(chunks: [DocumentChunk]) async throws
    /// Выполняет поиск ближайших чанков по эмбеддингу запроса.
    /// - Parameters:
    ///   - queryEmbedding: Вектор эмбеддинга поискового запроса.
    ///   - topK: Максимальное число лучших совпадений в ответе.
    /// - Returns: Отсортированные результаты поиска от наиболее релевантных к менее релевантным.
    /// - Throws: Ошибка выполнения поиска.
    func search(queryEmbedding: [Float], topK: Int) async throws -> [SearchResult]
}

/// Контракт фасада для высокоуровневых сценариев индексации, поиска и оценки стратегий чанкинга в RAG.
protocol RAGUseCaseFacadeProtocol {
    /// Индексирует набор документов с использованием выбранной стратегии чанкинга.
    /// - Parameters:
    ///   - documents: Файловые URL документов для индексации.
    ///   - strategy: Стратегия чанкинга, применяемая при индексации.
    /// - Returns: Сводная статистика и результаты индексации.
    /// - Throws: Ошибка, если индексация завершилась неуспешно на любом этапе конвейера.
    func index(documents: [URL], strategy: ChunkingStrategyType) async throws -> IndexingSummary
    /// Выполняет семантический поиск по проиндексированному корпусу.
    /// - Parameters:
    ///   - query: Исходный текст запроса пользователя.
    ///   - topK: Максимальное количество совпадений в ответе.
    /// - Returns: Ранжированные результаты поиска.
    /// - Throws: Ошибка генерации эмбеддинга запроса или поиска по векторам.
    func search(query: String, topK: Int) async throws -> [SearchResult]
    /// Сравнивает несколько стратегий чанкинга на датасете и наборе оценочных кейсов.
    /// - Parameters:
    ///   - strategies: Стратегии, которые нужно оценить.
    ///   - dataset: Файловые URL документов для индексации и оценки.
    ///   - evaluationCases: Эталонные оценочные кейсы для расчета метрик качества.
    ///   - topK: Количество результатов, учитываемых для каждого оценочного запроса.
    /// - Returns: Отчет с метриками по каждой стратегии и итоговым сравнением.
    /// - Throws: Ошибка, если не удалось выполнить индексацию, поиск или оценку.
    func compare(
        strategies: [ChunkingStrategyType],
        dataset: [URL],
        evaluationCases: [ChunkingEvaluationCase],
        topK: Int
    ) async throws -> ChunkingComparisonReport
    /// Полностью очищает хранилище векторного индекса и связанные записи.
    /// - Throws: Ошибка операции очистки.
    func resetIndex() async throws
}
